#!/usr/bin/env python3
"""
build-tools/previews.py — makes a shareable page for every public listing.

WHY
  Listing pages are drawn in the browser from js/data/builds.js. The raw page
  that Facebook, text messages, Discord and search engines read is generic, so a
  link to one PC previewed as "Gaming PC | Jacob Skrove PCs" with the same
  picture for every listing.

WHAT THIS DOES (runs as the last step of build-tools/stitch.py)
  For each AVAILABLE or SOLD listing it writes  pc-<id>.html  at the site root:
    - a copy of the finished build.html page (same header, footer, scripts),
    - with the listing's own title, description, canonical address, Open Graph /
      Twitter preview tags and schema.org Product data (price, availability) in
      the head, so the preview shows that PC,
    - and the listing id in  data-build-id  so the page shows that PC (the
      browser code in js/render/buildDetail.js reads it).
  The wording of the title and description is the SAME as the browser code sets
  (buildDetail.js), so no new site copy is introduced.
  It also writes images/share/<id>.jpg, a 1200x630 preview picture made from the
  listing's first photo (the whole photo on a blurred background, so a portrait
  photo is not cropped), then deletes pages and pictures of listings that are no
  longer public. Hand-made files are never touched: only pages that carry the
  marker comment below are replaced or deleted.

Needs Pillow for the preview pictures; without it the listing's own first photo
is used as the preview picture.
"""

import hashlib
import html
import json
import re
import sys
from pathlib import Path

try:
    from PIL import Image, ImageEnhance, ImageFilter
    PIL_OK = True
except ImportError:
    PIL_OK = False

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "build.html"
BUILDS_JS = ROOT / "js" / "data" / "builds.js"
SHARE_DIR = ROOT / "images" / "share"
MANIFEST = SHARE_DIR / "manifest.json"
STITCH = ROOT / "build-tools" / "stitch.py"

MARKER = "<!-- generated by build-tools/previews.py: do not edit; rebuilt on every publish -->"
PAGE_RE = re.compile(r"^pc-[a-z0-9-]+\.html$")
SHARE_W, SHARE_H = 1200, 630
SHARE_VERSION = "v1"             # bump to force every preview picture to be remade


def page_name(listing_id):
    return "pc-{}.html".format(listing_id)


def esc(value):
    return html.escape(str(value), quote=True)


def load_listings():
    if not BUILDS_JS.exists():
        return []
    src = BUILDS_JS.read_text(encoding="utf-8")
    if "const builds = " not in src:
        return []
    body = src.split("const builds = ", 1)[1].rstrip().rstrip(";")
    return [b for b in json.loads(body) if b.get("status") in ("available", "sold")]


def default_og_image():
    m = re.search(r'DEFAULT_OG_IMAGE\s*=\s*"([^"]+)"', STITCH.read_text(encoding="utf-8")) if STITCH.exists() else None
    return m.group(1) if m else "images/may26-01-main.jpg"


def first_photo(listing):
    for img in (listing.get("media") or {}).get("images") or []:
        if (ROOT / img).is_file():
            return img
    return None


def price_number(price_text):
    cleaned = re.sub(r"[^0-9.]", "", price_text or "")
    try:
        return "{:.2f}".format(float(cleaned)) if cleaned else None
    except ValueError:
        return None


def title_text(listing):
    # same wording as js/render/buildDetail.js
    return "{} | Jacob Skrove PCs".format(listing["title"])


def description_text(listing):
    # same wording as js/render/buildDetail.js
    return "{}, {}. Built and tested by Jacob Skrove PCs. Pickup in person near Grants Pass, Oregon.".format(
        listing["title"], listing.get("price", ""))


def json_ld(listing, page_url, image_urls):
    data = {
        "@context": "https://schema.org",
        "@type": "Product",
        "name": listing["title"],
        "url": page_url,
    }
    if image_urls:
        data["image"] = image_urls
    if listing.get("summary"):
        data["description"] = listing["summary"]
    price = price_number(listing.get("price"))
    if price:
        data["offers"] = {
            "@type": "Offer",
            "url": page_url,
            "priceCurrency": "USD",
            "price": price,
            "availability": "https://schema.org/InStock" if listing["status"] == "available" else "https://schema.org/SoldOut",
        }
    text = json.dumps(data, indent=2, ensure_ascii=False)
    return '<script type="application/ld+json">\n{}\n</script>'.format(text.replace("</", "<\\/"))


def head_block(site_url, listing, share_ok):
    page_url = "{}/{}".format(site_url, page_name(listing["id"]))
    photo = first_photo(listing)
    if share_ok:
        og_image = "{}/images/share/{}.jpg".format(site_url, listing["id"])
    elif photo:
        og_image = "{}/{}".format(site_url, photo)
    else:
        og_image = "{}/{}".format(site_url, default_og_image())
    title, desc = esc(title_text(listing)), esc(description_text(listing))
    lines = [
        '<link rel="canonical" href="{}">'.format(page_url),
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="Jacob Skrove PCs">',
        '<meta property="og:title" content="{}">'.format(title),
        '<meta property="og:description" content="{}">'.format(desc),
        '<meta property="og:url" content="{}">'.format(page_url),
        '<meta property="og:image" content="{}">'.format(og_image),
    ]
    if share_ok:
        lines += ['<meta property="og:image:width" content="{}">'.format(SHARE_W),
                  '<meta property="og:image:height" content="{}">'.format(SHARE_H),
                  '<meta property="og:image:alt" content="{}">'.format(esc(listing["title"]))]
    lines += [
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="{}">'.format(title),
        '<meta name="twitter:description" content="{}">'.format(desc),
        '<meta name="twitter:image" content="{}">'.format(og_image),
    ]
    photos = [p for p in (listing.get("media") or {}).get("images") or [] if (ROOT / p).is_file()][:4]
    lines.append(json_ld(listing, page_url, ["{}/{}".format(site_url, p) for p in photos]))
    return "\n".join(lines) + "\n"


def render_page(template, site_url, listing, share_ok):
    out = template
    # drop the generic canonical / Open Graph / Twitter lines, then put the listing's own in their place
    out = re.sub(r'^<link rel="canonical"[^\n]*\n', "", out, flags=re.M)
    out = re.sub(r'^<meta property="og:[^\n]*\n', "", out, flags=re.M)
    out = re.sub(r'^<meta name="twitter:[^\n]*\n', "", out, flags=re.M)
    anchor = '  <link rel="icon"'
    if out.count(anchor) != 1 or out.count('<div id="build-content"></div>') != 1 or "<title>" not in out:
        return None
    out = out.replace(anchor, head_block(site_url, listing, share_ok) + anchor)
    out = re.sub(r"<title>.*?</title>", lambda m: "<title>{}</title>".format(esc(title_text(listing))), out, count=1, flags=re.S)
    out = re.sub(r'<meta name="description" content="[^"]*">',
                 lambda m: '<meta name="description" content="{}">'.format(esc(description_text(listing))), out, count=1)
    out = out.replace('<div id="build-content"></div>', '<div id="build-content" data-build-id="{}"></div>'.format(esc(listing["id"])))
    return out.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + MARKER + "\n", 1)


def file_hash(path):
    return hashlib.sha1(path.read_bytes()).hexdigest()


def make_share_image(listing_id, photo, manifest):
    """1200x630 picture: the whole photo, centred, on a blurred darkened copy of itself. Returns True if usable."""
    if not PIL_OK or not photo:
        return False
    target = SHARE_DIR / "{}.jpg".format(listing_id)
    key = "{}:{}".format(SHARE_VERSION, file_hash(ROOT / photo))
    if target.is_file() and manifest.get(listing_id) == {"photo": photo, "key": key}:
        return True
    try:
        src = Image.open(ROOT / photo).convert("RGB")
        scale = max(SHARE_W / src.width, SHARE_H / src.height)
        bg = src.resize((int(src.width * scale) + 1, int(src.height * scale) + 1), Image.LANCZOS)
        left, top = (bg.width - SHARE_W) // 2, max(0, int((bg.height - SHARE_H) * 0.4))
        bg = bg.crop((left, top, left + SHARE_W, top + SHARE_H)).filter(ImageFilter.GaussianBlur(26))
        bg = ImageEnhance.Brightness(bg).enhance(0.42)
        fg = src.copy()
        fg.thumbnail((SHARE_W - 80, SHARE_H - 50), Image.LANCZOS)
        bg.paste(fg, ((SHARE_W - fg.width) // 2, (SHARE_H - fg.height) // 2))
        SHARE_DIR.mkdir(parents=True, exist_ok=True)
        bg.save(target, "JPEG", quality=84, optimize=True, progressive=True)
    except Exception as e:                                  # an unreadable photo must not stop publishing
        print("NOTE: could not make the preview picture for {} ({}); using the photo itself.".format(listing_id, e))
        return False
    manifest[listing_id] = {"photo": photo, "key": key}
    return True


def generate(site_url):
    """Write pc-<id>.html and images/share/<id>.jpg for public listings; remove stale ones. Returns the page names."""
    listings = load_listings()
    template = TEMPLATE.read_text(encoding="utf-8") if TEMPLATE.exists() else None
    manifest = {}
    if MANIFEST.exists():
        try:
            manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        except ValueError:
            manifest = {}

    pages, share_ids = [], set()
    if template is not None:
        for listing in sorted(listings, key=lambda b: b["id"]):
            share_ok = make_share_image(listing["id"], first_photo(listing), manifest)
            page = render_page(template, site_url, listing, share_ok)
            if page is None:
                print("NOTE: build.html doesn't have the expected shape; no listing pages were written.")
                pages = []
                break
            name = page_name(listing["id"])
            path = ROOT / name
            if not path.exists() or path.read_text(encoding="utf-8") != page:
                path.write_text(page, encoding="utf-8")
            pages.append(name)
            if share_ok:
                share_ids.add(listing["id"])

    # tidy: generated pages and pictures that no longer belong to a public listing
    for path in ROOT.glob("pc-*.html"):
        if PAGE_RE.match(path.name) and path.name not in pages and MARKER in path.read_text(encoding="utf-8")[:300]:
            path.unlink()
    if SHARE_DIR.is_dir():
        for pic in SHARE_DIR.glob("*.jpg"):
            if pic.stem not in share_ids:
                pic.unlink()
    manifest = {k: v for k, v in manifest.items() if k in share_ids}
    if share_ids:
        SHARE_DIR.mkdir(parents=True, exist_ok=True)
        text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
        if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != text:
            MANIFEST.write_text(text, encoding="utf-8")
    elif MANIFEST.exists():
        MANIFEST.unlink()
    return pages


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import stitch
    names = generate(stitch.get_site_url())
    print("Wrote {} listing page(s): {}".format(len(names), ", ".join(names) if names else "(none)"))
